import { test, expect } from '@playwright/test'
import { accountFor, mailVersion, mockGoogle, noOverflow, password, readMail, sendCode, verifyCode } from './auth-helpers.js'

test('signup verifies email before creating an account; email-first password sign-in sends no mail', async ({ page }, info) => {
  const email = `email-flow+${info.project.name}@example.test`
  await mockGoogle(page, email)
  await page.goto('/signup')
  await expect(page.getByLabel('Your name', { exact: true })).toHaveCount(0)
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  await page.getByLabel('Email address', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Send verification code', exact: true }).click()
  await expect(page.getByLabel('Verification code', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /Resend code in/ })).toBeDisabled()
  expect(accountFor(email)).toBeUndefined()
  expect((await (await page.request.get('/api/auth/session')).json()).user).toBeNull()
  await noOverflow(page)
  await verifyCode(page, email)
  expect(accountFor(email)).toBeUndefined()
  expect((await (await page.request.get('/api/auth/session')).json()).user).toBeNull()
  await page.getByLabel('Your name', { exact: true }).fill('Email Test Member')
  await page.getByLabel('New password', { exact: true }).fill(password)
  await page.getByLabel('Confirm new password', { exact: true }).fill('a different long passphrase')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('passwords do not match')
  expect(accountFor(email)).toBeUndefined()
  const oversizedPassword = '🔒'.repeat(70)
  await page.getByLabel('New password', { exact: true }).fill(oversizedPassword)
  await page.getByLabel('Confirm new password', { exact: true }).fill(oversizedPassword)
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('256 bytes')
  expect(accountFor(email)).toBeUndefined()
  await page.getByLabel('New password', { exact: true }).fill(password)
  await page.getByLabel('Confirm new password', { exact: true }).fill(password)
  const refresh = page.waitForResponse('/api/auth/session')
  await page.evaluate(() => window.dispatchEvent(new Event('focus')))
  await refresh
  await expect(page.getByLabel('Your name', { exact: true })).toHaveValue('Email Test Member')
  await expect(page.getByLabel('New password', { exact: true })).toHaveValue(password)
  const browserStorage = await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))
  expect(browserStorage).not.toContain(password)
  expect(browserStorage).not.toContain(readMail()[email])
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await expect(page.getByText('Password set', { exact: true })).toBeVisible()
  expect(accountFor(email).password_hash).toBeTruthy()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/signin$/)
  const authPosts = []
  page.on('request', (request) => { if (request.method() === 'POST' && /\/api\/auth\/(?!google\/nonce)/.test(request.url())) authPosts.push(new URL(request.url()).pathname) })
  const delivered = mailVersion()
  await expect(page.getByLabel('Password', { exact: true })).toHaveCount(0)
  await page.getByLabel('Email address', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Continue with email', exact: true }).click()
  await expect(page.getByLabel('Password', { exact: true })).toBeVisible()
  expect(authPosts).toEqual([]) // Email-first is UI only, not account discovery.
  await page.getByLabel('Password', { exact: true }).fill('incorrect password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('incorrect password')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  expect(mailVersion()).toBe(delivered)
  expect(authPosts).toEqual(['/api/auth/login', '/api/auth/login'])
  await expect(page.getByLabel('Verification code', { exact: true })).toHaveCount(0)
  await noOverflow(page)

  // The authoritative provider may safely link this verified local account.
  const existing = accountFor(email)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByRole('button', { name: 'Continue with Google', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  expect(mailVersion()).toBe(delivered)
  expect(accountFor(email).id).toBe(existing.id)
  expect(accountFor(email).password_hash).toBe(existing.password_hash)
  await expect(page.getByText('Password set', { exact: true })).toBeVisible()
  await expect(page.getByText('Linked', { exact: true })).toBeVisible()
})

test('Google directly establishes a session and a Google-only user can verify an optional password', async ({ page }, info) => {
  const email = `google-flow+${info.project.name}@example.test`
  await mockGoogle(page, email)
  let releaseGoogle
  const providerPending = new Promise((resolve) => { releaseGoogle = resolve })
  await page.route('**/api/auth/google', async (route) => { await providerPending; await route.continue() })
  await page.goto('/signin')
  const delivered = mailVersion()
  await page.getByRole('button', { name: 'Continue with Google', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Continue with Google…', exact: true })).toBeDisabled()
  await expect(page.getByLabel('Email address', { exact: true })).toBeDisabled()
  releaseGoogle()
  await expect(page).toHaveURL(/\/account$/)
  expect(mailVersion()).toBe(delivered)
  expect(readMail()[email]).toBeUndefined()
  await expect(page.getByLabel('Verification code', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Not set up', { exact: true })).toBeVisible()
  await expect(page.getByText('Linked', { exact: true })).toBeVisible()
  const before = accountFor(email)
  expect(before.password_hash).toBeNull()
  expect(before.google_sub).toBeTruthy()
  await page.getByRole('link', { name: 'Create a password' }).click()
  await expect(page).toHaveURL(/\/reset-password$/)
  await expect(page.getByLabel('Email address', { exact: true })).toHaveValue(email)
  await expect(page.getByRole('heading', { name: 'Create a password', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Send verification code', exact: true }).click()
  await expect(page.getByLabel('Verification code', { exact: true })).toBeVisible()
  await verifyCode(page, email)
  await expect(page.getByLabel('Your name', { exact: true })).toHaveCount(0)
  expect(accountFor(email).password_hash).toBeNull()
  await page.getByLabel('New password', { exact: true }).fill(password)
  await page.getByLabel('Confirm new password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Save password and sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  await expect(page.getByText('Password set', { exact: true })).toBeVisible()
  await expect(page.getByText('Linked', { exact: true })).toBeVisible()
  expect(accountFor(email).id).toBe(before.id)
  await page.getByRole('link', { name: 'Reset password' }).click()
  await expect(page).toHaveURL(/\/reset-password$/)
  await expect(page.getByLabel('Email address', { exact: true })).toHaveValue(email)
  await page.getByRole('link', { name: 'Back to your account' }).click()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByLabel('Email address', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Continue with email', exact: true }).click()
  await page.getByLabel('Password', { exact: true }).fill(password)
  const resetDelivery = mailVersion()
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/account$/)
  expect(mailVersion()).toBe(resetDelivery)
  await noOverflow(page)
})

test('code expiry, resend, back navigation and unavailable Google offer usable recovery', async ({ page }, info) => {
  // UI-only timing fixture: no fake verification or session succeeds here.
  let deliveries = 0
  await page.route('https://accounts.google.com/gsi/client', (route) => route.abort())
  await page.route('**/api/auth/signup', (route) => {
    deliveries += 1
    return route.fulfill({ status: 202, json: { challengeId: 'ui-expiry-fixture', expiresIn: 2, resendAfter: 2, message: 'If your details are eligible, a verification code has been sent. Check your inbox and spam folder.' } })
  })
  await page.goto('/signup')
  await expect(page.getByRole('alert')).toContainText('Google sign-in is unavailable')
  await expect(page.getByRole('button', { name: 'Retry Google sign-in', exact: true })).toBeEnabled()
  await page.getByLabel('Email address', { exact: true }).fill(`expiry+${info.project.name}@example.test`)
  await page.getByRole('button', { name: 'Send verification code', exact: true }).click()
  await expect(page.getByRole('button', { name: /Resend code in/ })).toBeDisabled()
  await expect(page.getByText(/This code has expired/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Verify and continue', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Resend verification code', exact: true }).click()
  expect(deliveries).toBe(2)
  await page.getByRole('button', { name: 'Change email', exact: true }).click()
  await expect(page.getByLabel('Email address', { exact: true })).toHaveValue(`expiry+${info.project.name}@example.test`)
  await noOverflow(page)
})

test('unknown-account recovery uses the generic response and keeps password entry behind verification', async ({ page }, info) => {
  const email = `unknown-reset+${info.project.name}@example.test`
  await sendCode(page, email, '/reset-password')
  await expect(page.getByRole('status').filter({ hasText: /If .* eligible/ })).toBeVisible()
  expect(readMail()[email]).toBeUndefined()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
  await page.getByLabel('Verification code', { exact: true }).fill('123456')
  await page.getByRole('button', { name: 'Verify and continue', exact: true }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  expect(accountFor(email)).toBeUndefined()
  await expect(page.locator('input[type=password]')).toHaveCount(0)
})
