import { test, expect } from '@playwright/test'
import { noOverflow, signUp } from './auth-helpers.js'

// These email/admin scenarios do not use Google. Keep its external provider
// unavailable rather than spending real nonce/rate-limit requests on unused UI.
test.beforeEach(async ({ page }) => {
  await page.route('https://accounts.google.com/gsi/client', (route) => route.abort())
})

test('authorized signup, event/member CRUD and homepage feature controls work end to end', async ({ page }, info) => {
  const failures = []
  page.on('pageerror', (error) => failures.push(error.message))
  await signUp(page, `admin+${info.project.name}@example.test`)
  await expect(page).toHaveURL(/\/admin$/)
  await expect(page.getByRole('button', { name: 'Add event', exact: true })).toBeEnabled()
  await noOverflow(page)
  await page.screenshot({ path: `test-results/admin-${info.project.name}.png`, fullPage: false })
  const title = `Browser ${info.project.name} Founders / Workshop #1`
  await page.getByRole('button', { name: 'Add event', exact: true }).click()
  await page.getByLabel('Title', { exact: false }).fill(title)
  await page.getByLabel('Display date').fill('March 8, 2030')
  await page.getByLabel('Archive year').fill('2030')
  await page.getByLabel('Short description').fill('A new event published through the admin panel.')
  await page.getByLabel('About the event', { exact: true }).fill('An event story managed from the dashboard.')
  await page.getByLabel('Featured on home page').check()
  await page.getByLabel('Display order').fill('0')
  await page.getByRole('button', { name: 'Publish event', exact: true }).click()
  await expect(page.getByText('Saved and published successfully.')).toBeVisible()
  await page.goto('/')
  await expect(page.locator('#events').getByRole('heading', { name: title })).toBeVisible()
  await page.locator('#events').getByRole('link').filter({ has: page.getByRole('heading', { name: title }) }).click()
  await expect(page.getByRole('heading', { level: 1, name: title })).toBeVisible()
  await expect(page.getByText('An event story managed from the dashboard.')).toBeVisible()
  await page.goto('/events')
  await expect(page.getByRole('button', { name: '2030', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '2030', exact: true }).click()
  await expect(page.getByRole('heading', { name: title })).toBeVisible()
  await page.goto('/admin')
  await page.getByRole('button', { name: `Edit ${title}`, exact: true }).click()
  await page.getByLabel('Featured on home page').uncheck()
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByText('Saved and published successfully.')).toBeVisible()
  await page.goto('/')
  await expect(page.locator('#events')).toBeVisible()
  await expect(page.locator('#events').getByRole('heading', { name: title })).toHaveCount(0)
  await page.goto('/admin')
  await page.getByRole('button', { name: /Team & volunteers/ }).click()
  await page.getByRole('button', { name: 'Add member', exact: true }).click()
  const name = `Featured ${info.project.name} Student`
  await page.getByLabel('Name', { exact: false }).fill(name)
  await page.getByLabel('Role', { exact: true }).fill('President')
  await page.locator('#content-batch').fill('2030-2031')
  await page.getByLabel('Featured on home page').check()
  await page.getByRole('button', { name: 'Publish member', exact: true }).click()
  await expect(page.getByText('Saved and published successfully.')).toBeVisible()
  await page.goto('/')
  await expect(page.locator('#team').getByRole('heading', { name })).toBeVisible()
  await page.goto('/teams')
  await expect(page.getByRole('button', { name: '2030-2031', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '2030-2031', exact: true }).click()
  await expect(page.getByRole('heading', { name })).toBeVisible()
  await page.goto('/admin')
  await page.getByRole('button', { name: /Team & volunteers/ }).click()
  await page.getByRole('button', { name: `Edit ${name}`, exact: true }).click()
  await page.getByLabel('Role', { exact: true }).fill('Mentor')
  await page.getByLabel('Featured on home page').uncheck()
  await page.getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(page.getByText('Saved and published successfully.')).toBeVisible()
  page.on('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: `Delete ${name}`, exact: true }).click()
  await expect(page.getByRole('button', { name: `Edit ${name}`, exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /^Events / }).click()
  await page.getByRole('button', { name: `Delete ${title}`, exact: true }).click()
  await expect(page.getByRole('button', { name: `Edit ${title}`, exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('button', { name: `Edit ${title}`, exact: true })).toHaveCount(0)
  await page.goto('/account')
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/signin$/)
  await page.goto('/admin')
  await expect(page).toHaveURL(/\/signin$/)
  expect(failures).toEqual([])
})

test('public navigation and non-admin access boundaries stay responsive', async ({ page }, info) => {
  await page.goto('/admin')
  await expect(page).toHaveURL(/\/signin$/)
  await noOverflow(page)
  await page.screenshot({ path: `test-results/signin-${info.project.name}.png`, fullPage: false })
  await signUp(page, `student+${info.project.name}@example.test`, 'Student Visitor')
  await expect(page).toHaveURL(/\/account$/)
  await expect(page.getByText('Your account does not have administrator access.')).toBeVisible()
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: 'For the authorized team.' })).toBeVisible()
  await noOverflow(page)
  const denial = await page.request.get('/api/admin/content')
  expect(denial.status()).toBe(403)
  for (const route of ['/', '/events', '/teams', '/contactus']) {
    await page.goto(route)
    await expect(page.locator('main')).toBeVisible()
    await noOverflow(page)
  }
})
